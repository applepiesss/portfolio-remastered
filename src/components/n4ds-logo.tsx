const SWING_DEG = 6;
const SWING_MS = 900; // one side-to-side pass
const STAGGER_MS = 140;

// Current rotation of an element in degrees, read from its computed transform matrix
const currentAngle = (el: Element) => {
  const m = new DOMMatrixReadOnly(getComputedStyle(el).transform);
  return (Math.atan2(m.b, m.a) * 180) / Math.PI;
};

const prefersReducedMotion = () => window.matchMedia("(prefers-reduced-motion: reduce)").matches;

export const N4dsLogo = ({ className, title = "N4ds", strokeWidth = 7 }: {
  className?: string;
  title?: string;
  /** In viewBox units; raise it when the logo is shown small so the lines don't get too thin */
  strokeWidth?: number;
}) => {
  // useId can contain characters that break url(#...) references, so keep only safe ones
  const gradientId = `n4ds-grad-${useId().replace(/[^a-zA-Z0-9_-]/g, "")}`;
  const letters = useRef<(SVGGElement | null)[]>([]);

  // Ease from wherever the letter is into a pendulum sway (fast through the middle, slow at the ends)
  const startSwing = () => {
    if (prefersReducedMotion()) return;
    letters.current.forEach((el, i) => {
      if (!el) return;
      const from = currentAngle(el);
      el.getAnimations().forEach((a) => a.cancel());
      const entry = el.animate([{ transform: `rotate(${from}deg)` }, { transform: `rotate(${SWING_DEG}deg)` }], {
        duration: SWING_MS / 2,
        delay: i * STAGGER_MS,
        easing: "ease-out",
        fill: "both",
      });
      entry.onfinish = () => {
        el.animate([{ transform: `rotate(${SWING_DEG}deg)` }, { transform: `rotate(${-SWING_DEG}deg)` }], {
          duration: SWING_MS,
          easing: "ease-in-out",
          direction: "alternate",
          iterations: Infinity,
        });
      };
    });
  };

  // Let each letter swing out a couple of smaller times from its current angle and come to rest
  const settle = () => {
    letters.current.forEach((el) => {
      if (!el) return;
      const from = currentAngle(el);
      el.getAnimations().forEach((a) => a.cancel());
      el.animate(
        [
          { transform: `rotate(${from}deg)` },
          { transform: `rotate(${-from * 0.45}deg)` },
          { transform: `rotate(${from * 0.15}deg)` },
          { transform: "rotate(0deg)" },
        ],
        { duration: 1100, easing: "ease-in-out" },
      );
    });
  };

  return (
    <svg
      viewBox="0 0 357 225"
      fill="none"
      stroke={`url(#${gradientId})`}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`n4ds-logo ${className ?? ""}`}
      onPointerEnter={startSwing}
      onPointerLeave={settle}
      role="img"
      aria-label={title}
    >
      <defs>
        <linearGradient id={gradientId} gradientUnits="userSpaceOnUse" x1="0" y1="30" x2="357" y2="195">
          <stop offset="0" style={{ stopColor: "var(--brand-grad-from)" }} />
          <stop offset="0.45" style={{ stopColor: "var(--brand-grad-via)" }} />
          <stop offset="1" style={{ stopColor: "var(--brand-grad-to)" }} />
        </linearGradient>
      </defs>
      {LETTERS.map((letter, i) => (
        <g key={letter.name} transform={`translate(${letter.dx} 0)`}>
          <g
            className="n4ds-letter"
            ref={(el) => {
              letters.current[i] = el;
            }}
          >
            {letter.paths.map((d) => (
              <path key={d} d={d} />
            ))}
          </g>
        </g>
      ))}
    </svg>
  );
};
